const pagesOk = (m) => m.pages.filter((p) => p.ok);
const home = (m) => m.pages[0];
const frac = (m, fn) => { const ps = pagesOk(m); return ps.length ? ps.filter(fn).length / ps.length : 0; };
const half = (x) => Math.round(x * 2) / 2;
const list = (a, n = 4) => a.slice(0, n).join(', ') + (a.length > n ? ` and ${a.length - n} more` : '');
const failing = (m, fn) => pagesOk(m).filter((p) => !fn(p)).map((p) => p.path);

