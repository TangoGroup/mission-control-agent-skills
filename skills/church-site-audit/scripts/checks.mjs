export function checkTotals() {
  const by = {};
  for (const c of CHECKS) by[c.cat] = (by[c.cat] || 0) + c.points;
  for (const k of CATEGORIES) if (by[k.id] !== k.points) throw new Error(`category ${k.id}: checks add to ${by[k.id]}, expected ${k.points}`);
  return CATEGORIES.reduce((s, k) => s + k.points, 0);
}
