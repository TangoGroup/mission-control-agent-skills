// The church website scorecard: 100 points, 10 categories, 43 checks.
// Single source of truth for score.mjs, report.mjs and `node score.mjs --rubric`.
//
// method 'measured': scored by measure.mjs output in a real browser, no judgement.
// method 'reviewed': scored by the auditor against the written levels, with quoted evidence.
// redesign: true when a new website fixes it by itself; false when it needs the church
// (current events, fresh photos, sermon uploads), so the projected score never over-promises.
// effort: 'quick' (under an hour on the current site), 'content' (the church writes or shoots
// something), 'design' (needs a redesign or a developer).
// bench: what the October 2026 study of 146 real church homepages found (30 small churches).

export const GRADES = [
  [90, 'Excellent', 'A site most churches would envy. Small refinements only.'],
  [75, 'Strong', 'Solid foundations with a few gaps that cost visitors.'],
  [60, 'Needs work', 'Visitors can find the basics, but the site makes them work for it.'],
  [40, 'Holding you back', 'The site is likely turning some visitors away before Sunday.'],
  [0, 'Urgent', 'The site is working against the church. Start here.'],
];
export const grade = (s) => GRADES.find(([min]) => s >= min);

